    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
         int fila = tableDatos.getSelectedRow();
    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione una fila primero.");
        return;
    }
    
    int id = (int) tableDatos.getValueAt(fila, 0); // Asumiendo que ID es la columna 0
    int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar el ID " + id + "?");
    
    if (confirm == JOptionPane.YES_OPTION) {
        try {
            if (controlador.eliminarCultivo(id)) {
                JOptionPane.showMessageDialog(this, "Eliminado correctamente.");
                listarCultivos();
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
    try {
        
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "⚠️ Primero seleccione un cultivo de la tabla para editar.");
            return;
        }
       
        DTOCultivo cultivoModificado = obtenerDatos();
        
        if (controlador.actualizarCultivo(cultivoModificado)) {
            JOptionPane.showMessageDialog(this, "✅ ¡Cultivo actualizado correctamente!");
            limpiar(); 
        } else {
            JOptionPane.showMessageDialog(this, "❌ No se pudo actualizar.");
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void tableDatosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableDatosMouseClicked
    int fila = tableDatos.getSelectedRow();
    
    if (fila >= 0) {
        try {
           
            txtId.setText(tableDatos.getValueAt(fila, 0).toString());
            txtNombre.setText(tableDatos.getValueAt(fila, 1).toString());
            cmbTipo.setSelectedItem(tableDatos.getValueAt(fila, 2));
            txtArea.setText(tableDatos.getValueAt(fila, 3).toString());
            cmbEstado.setSelectedItem(tableDatos.getValueAt(fila, 4));
    
            if (tableDatos.getValueAt(fila, 5) != null) {
                java.time.LocalDate fecha1 = (java.time.LocalDate) tableDatos.getValueAt(fila, 5);
                jDateChooser1.setDate(java.sql.Date.valueOf(fecha1));
            }

            if (tableDatos.getValueAt(fila, 6) != null) {
                java.time.LocalDate fecha2 = (java.time.LocalDate) tableDatos.getValueAt(fila, 6);
                jDateChooser2.setDate(java.sql.Date.valueOf(fecha2));
            }
            
        } catch (Exception e) {
            System.out.println("Error al cargar datos de la fila: " + e.getMessage());
            e.printStackTrace(); 
        }
    }
    }//GEN-LAST:event_tableDatosMouseClicked

    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
         try {
        String texto = txtBuscar.getText(); 
        List<DTOCultivo> resultados = controlador.buscar(texto);
        
        DefaultTableModel modelo = (DefaultTableModel) tableDatos.getModel();
        modelo.setRowCount(0);
        
        for (DTOCultivo c : resultados) {
            modelo.addRow(new Object[]{
                c.getIdCultivo(), c.getNombre(), c.getTipo(),
                c.getAreaSembrada(), c.getEstado(),
                c.getFechaSiembra(), c.getFechaCosecha()
            });
        }
    } catch (Exception e) {
   
       System.out.println("Error filtrando: " + e.getMessage());
    }
    }//GEN-LAST:event_txtBuscarKeyReleased

    
    

