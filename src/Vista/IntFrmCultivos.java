    private void listarCultivos() {
        try {
            DefaultTableModel modelo = (DefaultTableModel) tableDatos.getModel();
            modelo.setRowCount(0); 
            
            List<DTOCultivo> lista = controlador.listarCultivos();
            
            for (DTOCultivo c : lista) {
                modelo.addRow(new Object[]{
                    c.getIdCultivo(), 
                    c.getNombre(), 
                    c.getTipo(),
                    c.getAreaSembrada(), 
                    c.getEstado(),
                    c.getFechaSiembra(), 
                    c.getFechaCosecha()
                });
            }
        } catch (Exception ex) {
            System.err.println("Error al listar: " + ex.getMessage());
        }
    }

    private DTOCultivo obtenerDatos() throws Exception {
        DTOCultivo dto = new DTOCultivo();
        
       
        if (!txtId.getText().isEmpty()) {
            dto.setIdCultivo(Integer.parseInt(txtId.getText()));
        }
        
        if (txtNombre.getText().trim().isEmpty()) throw new Exception("El nombre es obligatorio.");
        
        if (jDateChooser1.getDate() == null) throw new Exception("Falta la fecha de siembra.");
        if (jDateChooser2.getDate() == null) throw new Exception("Falta la fecha de cosecha.");
        
        dto.setNombre(txtNombre.getText());
        
        try {
            dto.setAreaSembrada(Double.parseDouble(txtArea.getText()));
        } catch (NumberFormatException e) {
            throw new Exception("El área debe ser un número válido (ej: 10.5).");
        }
        
        dto.setTipo((TiposCultivo) cmbTipo.getSelectedItem());
        dto.setEstado((EstadoCrecimiento) cmbEstado.getSelectedItem());
        
        dto.setFechaSiembra(jDateChooser1.getDate().toInstant().atZone(ZoneId.systemDefault()).toLocalDate());
        dto.setFechaCosecha(jDateChooser2.getDate().toInstant().atZone(ZoneId.systemDefault()).toLocalDate());
            
        return dto;
    }
    
  
    private void limpiar() {
        txtId.setText(""); 
        txtNombre.setText(""); 
        txtArea.setText("");
        jDateChooser1.setDate(null); 
        jDateChooser2.setDate(null);
        listarCultivos(); 
    }
    
